-- Static snapshot of how many USD one unit of a currency is worth (analytics only).
CREATE TABLE exchange_rate (
    currency_code CHAR(3)        PRIMARY KEY,
    rate_to_usd   NUMERIC(18, 8) NOT NULL CHECK (rate_to_usd > 0),
    as_of         DATE           NOT NULL
);

CREATE TABLE employee (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code VARCHAR(20)    NOT NULL UNIQUE,
    full_name     VARCHAR(200)   NOT NULL,
    email         VARCHAR(254)   NOT NULL UNIQUE,
    job_title     VARCHAR(100)   NOT NULL,
    department    VARCHAR(100)   NOT NULL,
    country_code  CHAR(2)        NOT NULL,
    currency_code CHAR(3)        NOT NULL REFERENCES exchange_rate (currency_code),
    annual_salary NUMERIC(14, 2) NOT NULL CHECK (annual_salary >= 0),
    hire_date     DATE           NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL,
    updated_at    TIMESTAMPTZ    NOT NULL,
    version       BIGINT         NOT NULL DEFAULT 0
);

CREATE INDEX idx_employee_currency_code ON employee (currency_code);
