package com.acme.salary.employee;

import com.acme.salary.TestcontainersConfiguration;
import com.acme.salary.common.PageResponse;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.annotation.Import;
import org.springframework.data.domain.Sort;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDate;

import static org.assertj.core.api.Assertions.assertThat;

/** Directory search against real Postgres: the SQL generated by the specifications is what matters here. */
@SpringBootTest
@Import(TestcontainersConfiguration.class)
@Transactional
class EmployeeSearchTest {

    @Autowired
    private EmployeeRepository employees;

    @Autowired
    private EmployeeService service;

    @BeforeEach
    void seed() {
        employees.saveAll(java.util.List.of(
                employee("EMP-90001", "Asha Verma", "asha.verma@acme.com", "Engineering", "IN", "INR", "1500000"),
                employee("EMP-90002", "Rohan Iyer", "rohan.iyer@acme.com", "Engineering", "IN", "INR", "2500000"),
                employee("EMP-90003", "Emma Smith", "emma.smith@acme.com", "Sales", "US", "USD", "90000"),
                employee("EMP-90004", "Liam 100% Brown", "liam.brown@acme.com", "Engineering", "US", "USD", "150000")));
        employees.flush();
    }

    @Test
    void searchIsCaseInsensitiveAcrossNameEmailAndCode() {
        assertThat(names(search(new EmployeeFilter("ASHA", null, null, null)))).containsExactly("Asha Verma");
        assertThat(names(search(new EmployeeFilter("rohan.iyer@", null, null, null)))).containsExactly("Rohan Iyer");
        assertThat(names(search(new EmployeeFilter("emp-90003", null, null, null)))).containsExactly("Emma Smith");
    }

    @Test
    void filtersCombineWithAnd() {
        PageResponse<EmployeeResponse> result = search(new EmployeeFilter(null, "in", "Engineering", null));

        assertThat(names(result)).containsExactly("Asha Verma", "Rohan Iyer");
    }

    @Test
    void wildcardCharactersInSearchAreMatchedLiterally() {
        assertThat(names(search(new EmployeeFilter("100%", null, null, null)))).containsExactly("Liam 100% Brown");
        assertThat(search(new EmployeeFilter("_", null, null, null)).totalElements()).isZero();
    }

    @Test
    void paginatesAndSortsResults() {
        PageResponse<EmployeeResponse> firstPage = service.search(
                new EmployeeFilter("acme.com", null, null, null), 0, 3, EmployeeSortField.FULL_NAME, Sort.Direction.DESC);

        assertThat(firstPage.totalElements()).isEqualTo(4);
        assertThat(firstPage.totalPages()).isEqualTo(2);
        assertThat(names(firstPage)).containsExactly("Rohan Iyer", "Liam 100% Brown", "Emma Smith");
    }

    @Test
    void includesSalaryConvertedToUsd() {
        EmployeeResponse asha = search(new EmployeeFilter("EMP-90001", null, null, null)).content().getFirst();

        assertThat(asha.annualSalaryUsd()).isEqualByComparingTo("18000.00");
    }

    private PageResponse<EmployeeResponse> search(EmployeeFilter filter) {
        return service.search(filter, 0, 25, EmployeeSortField.FULL_NAME, Sort.Direction.ASC);
    }

    private static java.util.List<String> names(PageResponse<EmployeeResponse> page) {
        return page.content().stream().map(EmployeeResponse::fullName).toList();
    }

    private static Employee employee(String code, String name, String email, String department,
                                     String country, String currency, String salary) {
        return new Employee(code, name, email, "Software Engineer", department, country, currency,
                new BigDecimal(salary), LocalDate.of(2022, 4, 1));
    }
}
